def tracks_header(count: int) -> str:
    return f"📋 <b>Активные трекинги: {count}</b>\n"


def no_trackings() -> str:
    return (
        "Пока нет активных трекингов.\n"
        "Создайте первый через /track — это займёт полминуты."
    )


def web_admin_link(url: str) -> str:
    if url:
        return f"🖥 <b>Админ-панель</b>\n{escape(url)}"
    return (
        "🖥 <b>Админ-панель включена</b>, но публичный адрес не задан. "
        "Укажите <code>PUBLIC_URL</code> или откройте локальный адрес сервера "
        "(<code>/admin</code>)."
    )

def web_admin_link(url: str) -> str:
    return f"🖥 <b>Админ-панель</b>\n{escape(url)}" if url else (
        "🖥 Веб-админка отключена. Задайте <code>WEB_ENABLED=true</code> и пароль администратора."
    )
